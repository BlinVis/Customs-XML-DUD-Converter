"""Rebuild dud_converter/tarik_data.py from the TARIK tariff book (PDF).

Usage:
    pdftotext -layout TARIK2025.pdf tarik.txt
    python tools/build_tarik.py tarik.txt

Every line starting with a 10-digit "Kodi i mallrave" (e.g. "8421 2300 90") is
read: the first 8 digits are the tariff code, the last 2 the Precision_1 suffix.
An 8-digit code whose only subdivisions are 10 "for use in civil aviation" and
90 "others" is marked A, so the app can pick 90 for it.
"""

import re
import sys
from collections import defaultdict
from pathlib import Path

CODE_LINE = re.compile(r"^ {0,4}(\d{4}) ?(\d{4}) ?(\d{2})(?=\s{2,}|\s*$)(.*)")


def parse(lines):
    codes = defaultdict(dict)  # 8 digits -> {suffix: description}
    for i, line in enumerate(lines):
        m = CODE_LINE.match(line)
        if not m:
            continue
        rest = m[4].strip()
        desc = re.split(r"\s{3,}", rest)[0] if rest else (lines[i + 1].strip() if i + 1 < len(lines) else "")
        codes[m[1] + m[2]][m[3]] = desc
    return codes


def main(src):
    lines = Path(src).read_text(encoding="utf-8").splitlines()
    rows = []
    for code, subs in sorted(parse(lines).items()):
        mark = ""
        if set(subs) == {"10", "90"} and "aviacion" in subs["10"].lower():
            mark = " A"
        rows.append(f"{code} {','.join(sorted(subs))}{mark}")
    out = Path(__file__).resolve().parent.parent / "dud_converter" / "tarik_data.py"
    out.write_text(
        '"""Tariff code -> Precision_1 suffixes, from TARIK 2025. Generated by tools/build_tarik.py."""\n\n'
        "# <8-digit code> <suffixes>[ A]; A = only 10 (civil aviation) or 90 (others).\n"
        'DATA = """\\\n' + "\n".join(rows) + '\n"""\n',
        encoding="utf-8", newline="\n",
    )
    print(f"{len(rows)} codes written to {out}")


if __name__ == "__main__":
    main(sys.argv[1])
